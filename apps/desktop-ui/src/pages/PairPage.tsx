import { useEffect, useState, type FormEvent } from "react";
import { Link } from "react-router-dom";
import type { CapabilityReport, CommissionResult } from "@iotedu/contracts";
import { ApiError, api } from "../api";

export function PairPage() {
  const [caps, setCaps] = useState<CapabilityReport | null>(null);
  const [path, setPath] = useState<"new_device" | "smart_home">("smart_home");
  const [name, setName] = useState("");
  const [pairingCode, setPairingCode] = useState("");
  const [ack, setAck] = useState(false);
  const [result, setResult] = useState<CommissionResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api<CapabilityReport>("/api/capabilities")
      .then(setCaps)
      .catch((reason: Error) => setError(reason.message));
  }, []);

  const mock = !caps || caps.matterCommissioning === "mock_only";
  const identityReady = caps?.matterCommissioning === "available";

  async function submit(event: FormEvent) {
    event.preventDefault();
    setError(null);
    setResult(null);
    try {
      const body = await api<CommissionResult>("/api/nodes/commission", {
        method: "POST",
        body: JSON.stringify({
          path,
          name,
          pairingCode: pairingCode || undefined,
          confirm: true,
          ...(mock ? { acknowledgeSimulation: true } : {}),
        }),
      });
      setResult(body);
    } catch (reason) {
      setError(reason instanceof ApiError ? reason.message : "Commissioning failed");
    }
  }

  return (
    <section className="stack">
      <header>
        <h1>Pair New Node</h1>
        <p className="lede">The management fabric is an administrative Matter fabric. It does not create another Thread network.</p>
      </header>
      {mock ? (
        <div className="banner">
          This API is in mock mode. Submitting the form stores a simulated record and does not open a Matter session. Bluetooth commissioning is unsupported, and no Thread operational dataset is stored.
        </div>
      ) : (
        <div className="banner">
          Smart-home-first commissioning is the supported path. On Apple Home or another controller, turn on Matter pairing or sharing and copy the new code. IoT.Edu discovers the device on the existing Thread network and joins as an additional administrator. A brand-new board cannot be commissioned here until Bluetooth and a Thread operational dataset are both available.
        </div>
      )}
      {!mock && !identityReady && (
        <p className="banner">Create the management identity in Settings before commissioning. A missing identity is not generated by this form.</p>
      )}
      <form className="panel stack" onSubmit={submit}>
        <div className="row">
          <label>
            Path
            <select value={path} onChange={(event) => setPath(event.target.value as "new_device" | "smart_home")}>
              <option value="smart_home">Already in a smart-home ecosystem</option>
              <option value="new_device">Brand-new device</option>
            </select>
          </label>
          <label>
            Node name
            <input value={name} onChange={(event) => setName(event.target.value)} required />
          </label>
        </div>
        {path === "new_device" ? (
          <ol>
            <li>Confirm the initial firmware was written over USB. A finished write is not hardware verification until a board has booted.</li>
            <li>Bluetooth commissioning is not available in this Matter.js build.</li>
            <li>No Thread operational dataset is stored, and none will be invented.</li>
          </ol>
        ) : (
          <ol>
            <li>On the existing smart-home controller, enable Matter pairing or sharing.</li>
            <li>Copy the new commissioning code. It is redacted from logs.</li>
            <li>IoT.Edu discovers the device over the existing network and commissions a second administrator.</li>
            <li>After a CASE session, device identity and firmware fields are stored only when the device returns them.</li>
          </ol>
        )}
        <label>
          Pairing code
          <input value={pairingCode} onChange={(event) => setPairingCode(event.target.value)} autoComplete="off" required={!mock && path === "smart_home"} />
        </label>
        {mock && (
          <label className="row">
            <input type="checkbox" checked={ack} onChange={(event) => setAck(event.target.checked)} />
            I understand this creates a simulated local record and does not commission a device.
          </label>
        )}
        <button disabled={mock ? !ack || !name : !name || !identityReady} type="submit">
          {mock ? "Save simulated record" : path === "new_device" ? "Check new-device commissioning" : "Commission additional administrator"}
        </button>
      </form>
      {error && <p className="banner bad">{error}</p>}
      {result && (
        <div className="banner">
          <strong>{result.message}</strong>
          {result.limitation && <p>{result.limitation}</p>}
          <p>{result.matterSessionOpened ? "A management CASE session was opened." : "No live Matter session was opened."}</p>
          <Link className="button" to={`/nodes/${result.node.id}`}>Open node details</Link>
        </div>
      )}
    </section>
  );
}
